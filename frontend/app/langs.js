// First browser language we support; plain English only counts as a match when it's en-IN.
export function suggestLang() {
  for (const tag of globalThis.navigator?.languages || []) {
    const code = tag.slice(0, 2).toLowerCase();
    if (LANGS[code] && (code !== "en" || /-in$/i.test(tag))) return code;
  }
  return "hi";
}
